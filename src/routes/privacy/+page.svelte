                    <p>
                        This policy explains how Unify Ventures Pty Ltd (ABN 24
                        659 500 222) (<strong>Unify</strong>,
                        <strong>we</strong>) handles information in Unify AI,
                        including Unify Connect at connect.ai.unifyventures.vc
                        and the assistants that use it (together, the
                        <strong>Service</strong>). It applies to Unify's people
                        and to the people outside Unify who connect accounts to
                        the Service at our request. Last updated 29 October
                        2026.
                    </p>

                    <h3>What the Service does</h3>
                    <p>
                        Unify Connect lets a person connect accounts they hold
                        with other services, such as Google, Microsoft and Xero,
                        so that Unify's people and the software assistants they
                        approve can work with those accounts on their behalf:
                        reading and sending email, managing calendars and
                        documents, and preparing accounting records. Every
                        connection is made by the account holder, who chooses
                        what it may be used for, and can be ended at any time.
                    </p>

                    <h3>Information we collect</h3>
                    <ul>
                        <li>
                            <strong>When you sign in:</strong> your name, email address
                            and the identifier your Google or Microsoft account gives
                            us, so we know who you are.
                        </li>
                        <li>
                            <strong>When you connect an account:</strong> the account's
                            address or name (for a Xero account, its organisations'
                            names), the permissions you granted, and the credentials
                            the service issues for them.
                        </li>
                        <li>
                            <strong>When the Service is used:</strong> a record of
                            who connected, changed or used each account and when,
                            and technical logs needed to run and secure the Service.
                        </li>
                    </ul>

                    <h3>Google user data</h3>
                    <p>
                        When you connect a Google account you choose which of
                        these the Service may use, and it uses only those: Gmail
                        (to find, read, draft and send email you ask it to),
                        Google Calendar (to read and manage events), Google
                        Drive, Docs and Sheets (to find, read and write files),
                        and Google Contacts (to look up people).
                    </p>
                    <p>
                        This data is used only to carry out what you, or a Unify
                        person or assistant acting on your instructions, asks
                        for at the time. Unify Connect stores the credentials
                        for your account, not your email, events, files or
                        contacts: those are read from Google when a task needs
                        them, and kept only as long as that task does. To carry
                        out a task, the content involved may be processed by the
                        provider of the AI model an assistant runs on.
                    </p>
                    <p>
                        Unify AI's use and transfer of information received from
                        Google APIs to any other app will adhere to the
                        <a
                            href="https://developers.google.com/terms/api-services-user-data-policy"
                            >Google API Services User Data Policy</a
                        >, including the Limited Use requirements. In
                        particular, we do not:
                    </p>
                    <ul>
                        <li>sell Google user data;</li>
                        <li>
                            use or transfer it for advertising, including
                            personalised, retargeted or interest-based
                            advertising;
                        </li>
                        <li>
                            use it to determine creditworthiness or for lending;
                        </li>
                        <li>
                            use it to develop, improve or train generalised AI
                            or machine learning models;
                        </li>
                        <li>
                            allow people to read it, except with your consent
                            for a specific task, where needed for security or to
                            comply with the law, or where it has been aggregated
                            and anonymised for internal operations.
                        </li>
                    </ul>

                    <h3>Who we share information with</h3>
                    <p>
                        We do not sell personal information. We share it only
                        with the services that run Unify AI for us, and only as
                        far as they need: Nango, which holds the credentials for
                        connected accounts; Cloudflare, which serves Unify
                        Connect's web pages; Akamai (Linode), which hosts our
                        servers; and the providers of the AI models our
                        assistants run on, for the tasks you ask them to carry
                        out. We may also disclose information where the law
                        requires it.
                    </p>

                    <h3>How we protect it</h3>
                    <p>
                        Information is sent over encrypted connections.
                        Credentials and other secrets are stored encrypted.
                        Access to a connected account is limited to the
                        workspaces and assistants its holder or a Unify member
                        has approved, within the permissions granted, and every
                        use is recorded.
                    </p>

                    <h3>How long we keep it, and deleting it</h3>
                    <p>
                        A connected account's credentials are kept until it is
                        disconnected. Disconnecting an account in Unify Connect
                        ends all use of it and deletes its stored credentials;
                        you can also withdraw access at any time from the
                        service itself, for Google at
                        <a href="https://myaccount.google.com/permissions"
                            >myaccount.google.com/permissions</a
                        >. The record of what happened to an account is kept for
                        as long as we need it to account for its use. To ask for
                        your information, or for it to be deleted, email
                        <a href="mailto:hello@unifyventures.vc"
                            >hello@unifyventures.vc</a
                        >.
                    </p>

                    <h3>Contact</h3>
                    <p>
                        Questions about this policy or a complaint about how we
                        handle personal information can be sent to
                        <a href="mailto:hello@unifyventures.vc"
                            >hello@unifyventures.vc</a
                        >. We handle personal information in line with the
                        Privacy Act 1988 (Cth), and if you are not satisfied
                        with our response you can contact the Office of the
                        Australian Information Commissioner.
                    </p>
